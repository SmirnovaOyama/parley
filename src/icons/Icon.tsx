export type IconName = keyof typeof ICONS;

type Props = {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
  label?: string;
};

export function Icon({ name, size = 20, strokeWidth, className, style, label }: Props) {
  return (
    <svg
      className={className ? `oy-icon ${className}` : "oy-icon"}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      style={{ width: size, height: size, ...(strokeWidth ? { strokeWidth } : null), ...style }}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      {(ICONS[name] as Stroke[]).map((s, i) => {
        const stroke = typeof s === "string" ? { d: s } : s;
        return (
          <path
            key={i}
            d={stroke.d}
            fill={stroke.fill ? "currentColor" : undefined}
            strokeWidth={stroke.dot ? 2.6 : undefined}
          />
        );
      })}
    </svg>
  );
}
